export const candidateTotal = (c: Candidate) => c.filters.reduce((a, f) => a + f.score, 0) + c.bonus

/* قاعدة النقطة الوحدة: لو "بيقدر يدفع" أو "بتوصله" أخد نقطة واحدة، المرشح مستبعد */
export const candidatePassesRule = (c: Candidate) => {
  const pay = c.filters.find((f) => f.id === 'pay')?.score ?? 0
  const reach = c.filters.find((f) => f.id === 'reach')?.score ?? 0
  return pay > 1 && reach > 1
}

