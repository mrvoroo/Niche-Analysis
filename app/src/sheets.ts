export interface NicheSheet {
  id: string
  name: string
  fields: Record<string, string>
  scores: Record<string, number>
  bonus: number
  updatedAt: string
  deleted?: boolean
}

export const emptySheet = (name: string): NicheSheet => ({
  id: `s_${Date.now()}_${Math.random().toString(36).slice(2, 7)}`,
  name,
  fields: Object.fromEntries(SHEET_FIELDS.map((f) => [f.id, ''])),
  scores: Object.fromEntries(SCORE_FIELDS.map((f) => [f.id, 0])),
  bonus: 0,
  updatedAt: new Date().toISOString()
})

export const sheetTotal = (s: NicheSheet) =>
  SCORE_FIELDS.reduce((a, f) => a + (Number(s.scores[f.id]) || 0), 0) + (Number(s.bonus) || 0)

export const sheetFilled = (s: NicheSheet) =>
  SHEET_FIELDS.filter((f) => (s.fields[f.id] ?? '').trim().length > 0).length

/* قاعدة النقطة الوحدة */
export const sheetPassesRule = (s: NicheSheet) => {
  const pay = Number(s.scores.pay) || 0
  const reach = Number(s.scores.reach) || 0
  if (pay === 0 && reach === 0) return null // لسه ما اتقيّمش
  return pay > 1 && reach > 1
}

